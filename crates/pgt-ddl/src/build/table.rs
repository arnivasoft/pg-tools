fn ident_list(names: &[String]) -> String {
    names
        .iter()
        .map(|n| quote_ident(n))
        .collect::<Vec<_>>()
        .join(", ")
}

fn fk_action(a: FkAction) -> &'static str {
    match a {
        FkAction::NoAction => "NO ACTION",
        FkAction::Restrict => "RESTRICT",
        FkAction::Cascade => "CASCADE",
        FkAction::SetNull => "SET NULL",
        FkAction::SetDefault => "SET DEFAULT",
    }
}

/// Kolon tanımı: `ad tip [COLLATE] [IDENTITY] [GENERATED … AS (…)] [DEFAULT (…)] [NOT NULL]` (sabit sıra).
pub(crate) fn column_sql(c: &ColumnDef) -> String {
    // Tip metni `validate_type` ile doğrulandığından olduğu gibi yerleşir.
    let mut s = format!("{} {}", quote_ident(&c.name), c.data_type);
    if let Some(cl) = &c.collation {
        s.push_str(&format!(" COLLATE {}", quote_ident(cl)));
    }
    match c.identity {
        Some(IdentityKind::Always) => s.push_str(" GENERATED ALWAYS AS IDENTITY"),
        Some(IdentityKind::ByDefault) => s.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
        None => {}
    }
    if let Some(g) = &c.generated {
        s.push_str(&format!(
            " GENERATED ALWAYS AS {} {}",
            wrap(&g.expr),
            if g.stored { "STORED" } else { "VIRTUAL" }
        ));
    }
    if let Some(d) = &c.default {
        s.push_str(&format!(" DEFAULT {}", wrap(d)));
    }
    if c.not_null {
        s.push_str(" NOT NULL");
    }
    s
}

fn include_sql(include: &[String]) -> String {
    if include.is_empty() {
        String::new()
    } else {
        format!(" INCLUDE ({})", ident_list(include))
    }
}

/// Kısıt tanımı (tablo düzeyi). `not_valid` burada yazılmaz: create'te doğrulama hatasıdır (ADD için Task 3–4).
pub(crate) fn constraint_sql(c: &ConstraintDef) -> String {
    let mut s = match &c.name {
        Some(n) => format!("CONSTRAINT {} ", quote_ident(n)),
        None => String::new(),
    };
    match &c.kind {
        ConstraintKind::PrimaryKey { columns, include } => {
            s.push_str(&format!(
                "PRIMARY KEY ({}){}",
                ident_list(columns),
                include_sql(include)
            ));
        }
        ConstraintKind::Unique {
            columns,
            include,
            nulls_not_distinct,
        } => {
            s.push_str(&format!(
                "UNIQUE{} ({}){}",
                if *nulls_not_distinct {
                    " NULLS NOT DISTINCT"
                } else {
                    ""
                },
                ident_list(columns),
                include_sql(include)
            ));
        }
        ConstraintKind::Check { expr, no_inherit } => {
            s.push_str(&format!(
                "CHECK {}{}",
                wrap(expr),
                if *no_inherit { " NO INHERIT" } else { "" }
            ));
        }
        ConstraintKind::ForeignKey {
            columns,
            ref_schema,
            ref_table,
            ref_columns,
            match_type,
            on_update,
            on_delete,
        } => {
            // Eylemler her zaman açıkça yazılır (varsayılan NO ACTION dahil): çıktı deterministik ve okunur.
            s.push_str(&format!(
                "FOREIGN KEY ({}) REFERENCES {} ({}){} ON UPDATE {} ON DELETE {}",
                ident_list(columns),
                qualified(ref_schema, ref_table),
                ident_list(ref_columns),
                if *match_type == FkMatch::Full {
                    " MATCH FULL"
                } else {
                    ""
                },
                fk_action(*on_update),
                fk_action(*on_delete)
            ));
        }
    }
    if c.deferrable {
        s.push_str(" DEFERRABLE");
        if c.initially_deferred {
            s.push_str(" INITIALLY DEFERRED");
        }
    }
    s
}

fn partition_key_sql(k: &PartitionKey) -> String {
    match k {
        PartitionKey::Column { name } => quote_ident(name),
        // İfade anahtarı PG'de parantez ister; `wrap` hem bunu hem yorum güvenliğini sağlar.
        PartitionKey::Expression { sql } => wrap(sql),
    }
}

fn strategy_sql(s: PartitionStrategy) -> &'static str {
    match s {
        PartitionStrategy::Range => "RANGE",
        PartitionStrategy::List => "LIST",
        PartitionStrategy::Hash => "HASH",
    }
}

/// Ana `CREATE TABLE` ifadesi.
pub(crate) fn create_sql(d: &TableDef) -> String {
    let items: Vec<String> = d
        .columns
        .iter()
        .map(column_sql)
        .chain(d.constraints.iter().map(constraint_sql))
        .collect();
    let mut sql = format!(
        "CREATE {}TABLE {} (\n  {}\n)",
        if d.persistence == Persistence::Unlogged {
            "UNLOGGED "
        } else {
            ""
        },
        qualified(&d.schema, &d.name),
        items.join(",\n  ")
    );
    if let Some(p) = &d.partition_by {
        let keys: Vec<String> = p.keys.iter().map(partition_key_sql).collect();
        sql.push_str(&format!(
            " PARTITION BY {} ({})",
            strategy_sql(p.strategy),
            keys.join(", ")
        ));
    }
    if let Some(ff) = d.fillfactor {
        sql.push_str(&format!(" WITH (fillfactor = {ff})"));
    }
    if let Some(ts) = &d.tablespace {
        sql.push_str(&format!(" TABLESPACE {}", quote_ident(ts)));
    }
    sql
}

pub(crate) fn column_comment_sql(d: &TableDef, column: &str, comment: &Option<String>) -> String {
    let target = format!("{}.{}", qualified(&d.schema, &d.name), quote_ident(column));
    match comment {
        Some(c) => format!("COMMENT ON COLUMN {target} IS {}", quote_literal(c)),
        None => format!("COMMENT ON COLUMN {target} IS NULL"),
    }
}

pub(crate) fn table_comment_sql(q: &str, comment: &Option<String>) -> String {
    match comment {
        Some(c) => format!("COMMENT ON TABLE {q} IS {}", quote_literal(c)),
        None => format!("COMMENT ON TABLE {q} IS NULL"),
    }
}

