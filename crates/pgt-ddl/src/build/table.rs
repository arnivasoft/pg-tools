    #[test]
    fn drop_matrix() {
        let mut out = String::new();
        let cases: Vec<(&str, TableDef)> = vec![
            ("düz", base()),
            ("bölüm tablosu", TableDef { is_partition: true, ..base() }),
            ("bölümlenmiş tablo", parted()),
            ("anahtar sözcük", TableDef { schema: "My S".into(), name: "order".into(), ..base() }),
        ];
        for (label, d) in cases {
            for cascade in [false, true] {
                let p = bdrop(&o(d.clone()), cascade, &ctx()).unwrap();
                assert_single_statements(&p);
                assert_eq!(p.statements.len(), 1);
                let s = &p.statements[0];
                assert!(s.transactional);
                if cascade {
                    assert!(s.sql.ends_with(" CASCADE"));
                    assert_eq!(s.risk, Risk::DataLoss);
                    assert_eq!(p.warnings, [CASCADE_WARNING]);
                } else {
                    assert!(!s.sql.contains("CASCADE"));
                    assert_eq!(s.risk, Risk::Destructive);
                    assert!(p.warnings.is_empty());
                }
                out.push_str(&format!("## {label} cascade={cascade}\n{}\n", render(&p)));
            }
        }
        insta::assert_snapshot!(out);
        assert_eq!(sqls(&bdrop(&o(base()), false, &ctx()).unwrap()), ["DROP TABLE public.t"]);
        assert_eq!(sqls(&bdrop(&o(base()), true, &ctx()).unwrap()), ["DROP TABLE public.t CASCADE"]);
    }

