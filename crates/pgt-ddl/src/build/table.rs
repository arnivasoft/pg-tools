//! Tablo üreticisi: CREATE (kolonlar, kısıtlar, bölümleme, sürüm kapıları) ve DROP. Alter `table_alter.rs`'te.
//!
//! Kararlar:
//! - Ad alanları (tablo/şema/sahip/tablespace/kolon/kısıt/collation/FK hedefi/bölüm kolonu) yalnızca `quote_ident` ya da
//!   `qualified` ile yerleşir; `collation` (indeksteki gibi) TEK tanımlayıcıdır, şema nitelikli collation kapsam dışıdır.
//! - Veri tipi metni `validate_type` dilbilgisinden geçtikten sonra olduğu gibi yerleşir.
//! - Serbest SQL alanları (varsayılan, üretilmiş ifade, CHECK, bölüm ifadesi, `using`) `check_free_sql`'den geçer ve
//!   `wrap` ile `(… \n)` biçiminde yerleşir; birleşmiş NİHAİ `CREATE TABLE` ifadesi de `composed_is_clean` ile taranır.
//! - Kolon ve kısıt satırları arasındaki `,\n  ` ayracı ve kapanıştaki `\n)` YAPISALDIR (okunabilirlik); serbest SQL
//!   alanlarının kendi sarmalı bundan bağımsızdır.
//! - Doğrulama iki katmanlıdır: `validate_table` (create ve alter'ın yeni tarafı için ortak) ve `validate_create`
//!   (yalnızca yeni tanıma özgü kurallar: `notValid`, `using`, `isPartition`, `inherits` + nihai ifade taraması).
//! - Sunucuda kesin bildiğimiz kurallar burada hata olarak kodlanır; emin olmadıklarımız (aşağıda tek tek not edildi)
//!   sunucuya bırakılır: uygulama transaction içinde çalışır ve hata geri alınır.

