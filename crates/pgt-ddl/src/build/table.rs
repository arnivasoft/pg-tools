/// Ad, `check_ident` kurallarını geçiyor mu (hata eklemeden). Yinelenme/eksiklik iletileri adı yalnızca geçerliyse
/// içerir; geçersiz ad zaten kendi alanında tek hata alır.
fn ident_ok(v: &str) -> bool {
    let mut t = vec![];
    check_ident("", v, &mut t);
    t.is_empty()
}

pub(crate) fn version_err(path: &str, what: &str, major: u32) -> FieldError {
    err(path, format!("{what} PG {major}+ gerektirir."))
}

fn validate_column(i: usize, c: &ColumnDef, ctx: &BuildCtx, e: &mut Vec<FieldError>) {
    let p = |f: &str| format!("columns[{i}].{f}");
    check_ident(&p("name"), &c.name, e);
    if let Err(m) = validate_type(&c.data_type) {
        e.push(err(&p("dataType"), m));
    }
    if let Some(cl) = &c.collation {
        check_ident(&p("collation"), cl, e);
    }
    if let Some(cm) = &c.comment {
        check_text(&p("comment"), cm, e);
    }
    if let Some(u) = &c.using {
        check_free_sql(&p("using"), u, e);
    }
    // Kimlik tamsayı tip ister (smallint/integer/bigint ve takma adları): tip takma adları/alan tipleri nedeniyle
    // sunucuya bırakılır.
    if c.identity.is_some() && ctx.version_num < 100000 {
        e.push(version_err(&p("identity"), "Kimlik kolonu (GENERATED … AS IDENTITY)", 10));
    }
    if let Some(g) = &c.generated {
        let before = e.len();
        check_free_sql(&p("generated"), &g.expr, e);
        if e.len() == before {
            if c.identity.is_some() {
                e.push(err(
                    &p("generated"),
                    "Kolon hem kimlik hem üretilmiş olamaz.",
                ));
            } else if g.stored && ctx.version_num < 120000 {
                e.push(version_err(&p("generated"), "Üretilmiş kolon (STORED)", 12));
            } else if !g.stored && ctx.version_num < 180000 {
                e.push(version_err(&p("generated"), "Sanal üretilmiş kolon (VIRTUAL)", 18));
            }
        }
    }
    if let Some(dv) = &c.default {
        let before = e.len();
        check_free_sql(&p("default"), dv, e);
        if e.len() == before {
            if c.identity.is_some() {
                e.push(err(
                    &p("default"),
                    "Kimlik kolonu varsayılan değer alamaz.",
                ));
            } else if c.generated.is_some() {
                e.push(err(
                    &p("default"),
                    "Üretilmiş kolon varsayılan değer alamaz.",
                ));
            }
        }
    }
}

/// Kısıtın kolon listesini doğrular: boş değil, her ad geçerli, tabloda var (büyük/küçük harf duyarlı) ve
/// `reject_dups` ise yinelenmiyor.
fn check_column_list(
    path: &str,
    cols: &[String],
    table_cols: &HashSet<&str>,
    reject_dups: bool,
    e: &mut Vec<FieldError>,
) {
    if cols.is_empty() {
        e.push(err(path, "En az bir kolon gerekli."));
        return;
    }
    let mut seen = HashSet::new();
    for (j, c) in cols.iter().enumerate() {
        let pj = format!("{path}[{j}]");
        let before = e.len();
        check_ident(&pj, c, e);
        if e.len() != before {
            continue;
        }
        if !table_cols.contains(c.as_str()) {
            e.push(err(&pj, format!("'{c}' kolonu tabloda yok.")));
        } else if !seen.insert(c.as_str()) && reject_dups {
            e.push(err(&pj, format!("'{c}' kolonu listede birden fazla.")));
        }
    }
}

fn check_include(i: usize, include: &[String], table_cols: &HashSet<&str>, ctx: &BuildCtx, e: &mut Vec<FieldError>) {
    if include.is_empty() {
        return;
    }
    let path = format!("constraints[{i}].include");
    if ctx.version_num < 110000 {
        e.push(version_err(&path, "INCLUDE", 11));
    }
    let mut seen = HashSet::new();
    for (j, c) in include.iter().enumerate() {
        let pj = format!("{path}[{j}]");
        let before = e.len();
        check_ident(&pj, c, e);
        if e.len() != before {
            continue;
        }
        if !table_cols.contains(c.as_str()) {
            e.push(err(&pj, format!("'{c}' kolonu tabloda yok.")));
        } else if !seen.insert(c.as_str()) {
            e.push(err(&pj, format!("'{c}' kolonu INCLUDE listesinde birden fazla.")));
        }
    }
}

fn validate_constraint(
    i: usize,
    c: &ConstraintDef,
    d: &TableDef,
    table_cols: &HashSet<&str>,
    ctx: &BuildCtx,
    e: &mut Vec<FieldError>,
) {
    let p = |f: &str| format!("constraints[{i}].{f}");
    if let Some(n) = &c.name {
        check_ident(&p("name"), n, e);
    }
    let partitioned = d.partition_by.as_ref();
    match &c.kind {
        ConstraintKind::PrimaryKey { columns, include }
        | ConstraintKind::Unique {
            columns, include, ..
        } => {
            check_column_list(&p("columns"), columns, table_cols, true, e);
            check_include(i, include, table_cols, ctx, e);
            if let ConstraintKind::Unique {
                nulls_not_distinct: true,
                ..
            } = c.kind
                && ctx.version_num < 150000
            {
                e.push(version_err(&p("nullsNotDistinct"), "NULLS NOT DISTINCT", 15));
            }
            if let Some(pb) = partitioned {
                let what = if matches!(c.kind, ConstraintKind::PrimaryKey { .. }) {
                    "PRIMARY KEY"
                } else {
                    "UNIQUE"
                };
                if ctx.version_num < 110000 {
                    // PG 10: bölümlenmiş tabloda benzersiz indeks yok → PK/UNIQUE desteklenmez.
                    e.push(err(
                        &format!("constraints[{i}]"),
                        format!("Bölümlenmiş tabloda {what} kısıtı PG 11+ gerektirir."),
                    ));
                } else if pb
                    .keys
                    .iter()
                    .any(|k| matches!(k, PartitionKey::Expression { .. }))
                {
                    // PG 11+: bölüm anahtarında ifade varsa PK/UNIQUE kurulamaz.
                    e.push(err(
                        &p("columns"),
                        format!("Bölüm anahtarı ifade içerdiğinden {what} kısıtı kurulamaz."),
                    ));
                } else if let Some(missing) = pb.keys.iter().find_map(|k| match k {
                    // Geçersiz bölüm kolonu adı kendi alanında raporlanır; iletiye yalnızca geçerli ad girer.
                    PartitionKey::Column { name } if ident_ok(name) && !columns.contains(name) => Some(name),
                    _ => None,
                }) {
                    // PG 11+: benzersizlik kısıtı tüm bölüm kolonlarını içermeli.
                    e.push(err(
                        &p("columns"),
                        format!("{what} kısıtı tüm bölüm kolonlarını içermeli ('{missing}' eksik)."),
                    ));
                }
            }
        }
        ConstraintKind::Check { expr, no_inherit } => {
            check_free_sql(&p("expr"), expr, e);
            if *no_inherit && partitioned.is_some() {
                e.push(err(
                    &p("noInherit"),
                    "Bölümlenmiş tabloda CHECK kısıtı NO INHERIT olamaz.",
                ));
            }
            if c.deferrable {
                e.push(err(
                    &p("deferrable"),
                    "CHECK kısıtı DEFERRABLE olamaz.",
                ));
            }
        }
        ConstraintKind::ForeignKey {
            columns,
            ref_schema,
            ref_table,
            ref_columns,
            ..
        } => {
            // PG yerel kolon listesinde yinelenmeye izin verir (yalnızca hedef listede reddeder); yüklenmiş böyle bir
            // FK alter'ın yeni tarafında reddedilmesin diye burada da serbest.
            check_column_list(&p("columns"), columns, table_cols, false, e);
            check_schema_ident(&p("refSchema"), ref_schema, e);
            check_ident(&p("refTable"), ref_table, e);
            // Hedef tablonun kolonları sunucuda doğrulanır; burada yalnızca adlar ve sayı.
            if ref_columns.is_empty() {
                e.push(err(&p("refColumns"), "En az bir hedef kolon gerekli."));
            } else {
                let mut seen = HashSet::new();
                for (j, rc) in ref_columns.iter().enumerate() {
                    let pj = format!("constraints[{i}].refColumns[{j}]");
                    let before = e.len();
                    check_ident(&pj, rc, e);
                    // PG: "foreign key referenced-columns list must not contain duplicates".
                    if e.len() == before && !seen.insert(rc.as_str()) {
                        e.push(err(&pj, format!("'{rc}' kolonu hedef listede birden fazla.")));
                    }
                }
                if !columns.is_empty() && columns.len() != ref_columns.len() {
                    e.push(err(
                        &p("refColumns"),
                        "Hedef kolon sayısı yerel kolon sayısına eşit olmalı.",
                    ));
                }
            }
            if partitioned.is_some() && ctx.version_num < 110000 {
                // PG 10: bölümlenmiş tablodan yabancı anahtar desteklenmez (PG 11+ destekler). Bölümlenmiş tabloya
                // BAŞVURAN yabancı anahtar PG 12+ ister; hedefin bölümlü olup olmadığı burada bilinmez → sunucuda.
                e.push(err(
                    &format!("constraints[{i}]"),
                    "Bölümlenmiş tabloda FOREIGN KEY kısıtı PG 11+ gerektirir.",
                ));
            }
        }
    }
    if c.initially_deferred && !c.deferrable {
        e.push(err(
            &p("initiallyDeferred"),
            "INITIALLY DEFERRED yalnızca DEFERRABLE kısıtta kullanılabilir.",
        ));
    }
    if c.not_valid
        && matches!(
            c.kind,
            ConstraintKind::PrimaryKey { .. } | ConstraintKind::Unique { .. }
        )
    {
        e.push(err(
            &p("notValid"),
            "NOT VALID yalnızca FOREIGN KEY ve CHECK kısıtlarında kullanılabilir.",
        ));
    }
}

fn validate_partition(d: &TableDef, table_cols: &HashSet<&str>, ctx: &BuildCtx, e: &mut Vec<FieldError>) {
    let Some(pb) = &d.partition_by else { return };
    if ctx.version_num < 100000 {
        e.push(version_err("partitionBy", "Bölümlenmiş tablo", 10));
        return;
    }
    if pb.strategy == PartitionStrategy::Hash && ctx.version_num < 110000 {
        e.push(version_err("partitionBy.strategy", "PARTITION BY HASH", 11));
    }
    if pb.keys.is_empty() {
        e.push(err("partitionBy.keys", "En az bir bölüm anahtarı gerekli."));
    }
    for (j, k) in pb.keys.iter().enumerate() {
        let pj = format!("partitionBy.keys[{j}]");
        match k {
            PartitionKey::Column { name } => {
                let before = e.len();
                check_ident(&pj, name, e);
                if e.len() == before && !table_cols.contains(name.as_str()) {
                    e.push(err(&pj, format!("'{name}' kolonu tabloda yok.")));
                }
            }
            PartitionKey::Expression { sql } => check_free_sql(&pj, sql, e),
        }
    }
    // Gerçek sunucuda doğrulandı (Task 5, PG 10–18):
    // - PG 18 "partitioned tables cannot be unlogged"; PG 10–17 kabul eder (relpersistence = 'u' yüklenir).
    if d.persistence == Persistence::Unlogged && ctx.version_num >= 180000 {
        e.push(err("persistence", PARTITIONED_UNLOGGED_MSG));
    }
    // - PG 10–11 bölümlenmiş tablonun TABLESPACE'ini sessizce yoksayar (reltablespace 0 kalır → gidiş-dönüş bozulur);
    //   PG 12+ "cannot specify default tablespace for partitioned relations" (veritabanının varsayılanı pg_default).
    // Kapı yaklaşıktır: sunucu belirtilen tablespace'i VERİTABANININ varsayılan tablespace'iyle karşılaştırır, `pg_default`
    // adıyla değil. Varsayılanı başka olan veritabanında `pg_default` aslında kabul edilir, varsayılan olan başka bir ad
    // ise sunucuda reddedilir (uygulama geri alınır). Yerelde veritabanının varsayılanı bilinmez.
    if let Some(ts) = &d.tablespace {
        if ctx.version_num < 120000 {
            e.push(version_err("tablespace", "Bölümlenmiş tabloda TABLESPACE", 12));
        } else if ts == "pg_default" {
            e.push(err(
                "tablespace",
                "Bölümlenmiş tabloda varsayılan tablespace (pg_default) açıkça belirtilemez; boş bırakın.",
            ));
        }
    }
}

pub(crate) const PARTITIONED_UNLOGGED_MSG: &str =
    "PG 18+ bölümlenmiş tablo UNLOGGED olamaz (bölümler ayrı ayrı UNLOGGED yapılabilir).";

/// Tablo bölümlenmiş mi: istemcinin kurduğu tanımda `partition_by`, yüklenmiş tanımda `partition_text` dolu.
pub(crate) fn is_partitioned(d: &TableDef) -> bool {
    d.partition_by.is_some() || d.partition_text.is_some()
}

/// Ortak tablo doğrulaması (create ve alter'ın yeni tarafı). Hata sırası sabittir: tablo alanları, kolonlar,
/// kısıtlar, bölümleme, fillfactor.
pub fn validate_table(d: &TableDef, ctx: &BuildCtx) -> Vec<FieldError> {
    let mut e = vec![];
    check_ident("name", &d.name, &mut e);
    check_schema_ident("schema", &d.schema, &mut e);
    if let Some(o) = &d.owner {
        check_ident("owner", o, &mut e);
    }
    if let Some(ts) = &d.tablespace {
        // `pg_default` geçerli bir addır (varsayılan tablespace'e açıkça dönmek için).
        check_ident("tablespace", ts, &mut e);
    }
    if let Some(c) = &d.comment {
        check_text("comment", c, &mut e);
    }
    // "En az bir kolon" yalnızca create kuralıdır (`validate_create`): PG kolonsuz tabloya izin verir ve bir tablo
    // alter ile tüm kolonlarını kaybedebilir.
    let mut seen_cols = HashSet::new();
    for (i, c) in d.columns.iter().enumerate() {
        validate_column(i, c, ctx, &mut e);
        // Adlar tırnaklı yerleştiğinden karşılaştırma büyük/küçük harfe duyarlıdır ("A" ile "a" farklı kolondur).
        // Geçersiz ad kendi hatasını almıştır: yinelenme yalnızca geçerli adlar için (aynı yolda çift hata yok).
        if ident_ok(&c.name) && !seen_cols.insert(c.name.as_str()) {
            e.push(err(
                &format!("columns[{i}].name"),
                format!("'{}' kolonu birden fazla tanımlı.", c.name),
            ));
        }
    }
    let table_cols: HashSet<&str> = d.columns.iter().map(|c| c.name.as_str()).collect();
    let mut seen_cons = HashSet::new();
    let mut has_pk = false;
    for (i, c) in d.constraints.iter().enumerate() {
        validate_constraint(i, c, d, &table_cols, ctx, &mut e);
        if let Some(n) = &c.name
            && ident_ok(n)
            && !seen_cons.insert(n.as_str())
        {
            e.push(err(
                &format!("constraints[{i}].name"),
                format!("'{n}' kısıt adı birden fazla kullanılmış."),
            ));
        }
        if matches!(c.kind, ConstraintKind::PrimaryKey { .. }) {
            if has_pk {
                e.push(err(
                    &format!("constraints[{i}]"),
                    "Tabloda en çok bir PRIMARY KEY olabilir.",
                ));
            }
            has_pk = true;
        }
    }
    // PG kimlik ve PRIMARY KEY kolonlarını her zaman NOT NULL yapar; `notNull: false` yüklemede `true` döner ve
    // "değiştirmeden düzenle → boş plan" eşitliğini bozardı. Tanım bunu açıkça taşımalı.
    let pk_cols: HashSet<&str> = d
        .constraints
        .iter()
        .filter_map(|c| match &c.kind {
            ConstraintKind::PrimaryKey { columns, .. } => Some(columns),
            _ => None,
        })
        .flatten()
        .map(String::as_str)
        .collect();
    for (i, c) in d.columns.iter().enumerate() {
        if !c.not_null && (c.identity.is_some() || pk_cols.contains(c.name.as_str())) {
            e.push(err(
                &format!("columns[{i}].notNull"),
                "Kimlik/PRIMARY KEY kolonu her zaman NOT NULL'dır; notNull işaretli olmalı.",
            ));
        }
    }
    validate_partition(d, &table_cols, ctx, &mut e);
    if let Some(ff) = d.fillfactor {
        if d.partition_by.is_some() {
            // PG 10+: "cannot specify storage parameters for a partitioned table" (aralık hatası ayrıca verilmez).
            e.push(err(
                "fillfactor",
                "Bölümlenmiş tabloda fillfactor belirtilemez.",
            ));
        } else if !(10..=100).contains(&ff) {
            e.push(err(
                "fillfactor",
                "Doldurma oranı 10 ile 100 arasında olmalı.",
            ));
        }
    }
    e
}

/// Oluşturma doğrulaması: ortak kurallar + yalnızca yeni tanıma özgü kurallar + nihai ifade taraması.
pub(crate) fn validate_create(d: &TableDef, ctx: &BuildCtx) -> Vec<FieldError> {
    let mut e = validate_table(d, ctx);
    if d.columns.is_empty() {
        // Ortak hataların önüne: kolonsuz tanımda ilk hata budur.
        e.insert(0, err("columns", "En az bir kolon gerekli."));
    }
    const LOADED: &str = "Yüklenmiş tanım yeniden oluşturulamaz; oluşturma yalnızca yeni tablo içindir.";
    if d.is_partition {
        e.push(err("isPartition", LOADED));
    }
    if d.inherits {
        e.push(err("inherits", LOADED));
    }
    for (i, c) in d.columns.iter().enumerate() {
        let path = format!("columns[{i}].using");
        // Serbest SQL hatası zaten bu yolda raporlandıysa ikinci hata eklenmez.
        if c.using.is_some() && !e.iter().any(|x| x.path == path) {
            e.push(err(
                &path,
                "USING yalnızca mevcut kolonun tipini değiştirirken kullanılabilir.",
            ));
        }
    }
    for (i, c) in d.constraints.iter().enumerate() {
        if c.not_valid && matches!(c.kind, ConstraintKind::ForeignKey { .. } | ConstraintKind::Check { .. }) {
            e.push(err(
                &format!("constraints[{i}].notValid"),
                "NOT VALID yalnızca mevcut tabloya kısıt eklerken kullanılabilir.",
            ));
        }
    }
    // Nihai ifade: alan sınırlarında bölge/parantez kaymasını yakalar (ifade sonunda `;` yoktur).
    if e.is_empty() && !composed_is_clean(&create_sql(d)) {
        e.push(err(
            "columns",
            "Serbest SQL alanları birleşince geçersiz ifade oluşuyor (ör. satır yorumuyla biten ifade).",
        ));
    }
    e
}

