/// Yorum dolu mu: `Some("")` `None` sayılır. PG'de `COMMENT … IS ''` yorumu siler; yükleyici yorumsuz nesne için
/// `None` döndürür, bu yüzden boş yorum için ifade üretilmez.
pub(crate) fn has_comment(c: &Option<String>) -> bool {
    c.as_deref().is_some_and(|s| !s.is_empty())
}

/// Sıra: CREATE TABLE, sahip, tablo yorumu, kolon yorumları (yalnızca dolu olanlar, kolon sırasıyla). Hepsi Safe.
pub fn create(d: &TableDef) -> Plan {
    let q = qualified(&d.schema, &d.name);
    let mut statements = vec![stmt(create_sql(d), Risk::Safe, None)];
    if let Some(o) = &d.owner {
        statements.push(stmt(
            format!("ALTER TABLE {q} OWNER TO {}", quote_ident(o)),
            Risk::Safe,
            None,
        ));
    }
    if has_comment(&d.comment) {
        statements.push(stmt(table_comment_sql(&q, &d.comment), Risk::Safe, None));
    }
    for c in &d.columns {
        if has_comment(&c.comment) {
            statements.push(stmt(
                column_comment_sql(d, &c.name, &c.comment),
                Risk::Safe,
                None,
            ));
        }
    }
    Plan {
        statements,
        warnings: vec![],
    }
}

pub fn drop(d: &TableDef, cascade: bool) -> Plan {
    let q = qualified(&d.schema, &d.name);
    let mut notes: Vec<&str> = vec![];
    if cascade {
        notes.push(CASCADE_WARNING);
    }
    if d.is_partition {
        notes.push(PARTITION_DROP_NOTE);
    }
    // Yüklenmiş bölümlenmiş tabloda `partition_by` boştur; `partition_text` dolu.
    if is_partitioned(d) {
        notes.push(PARTITIONED_DROP_NOTE);
    }
    let note = (!notes.is_empty()).then(|| notes.join("; "));
    let (sql, risk) = if cascade {
        (format!("DROP TABLE {q} CASCADE"), Risk::DataLoss)
    } else {
        (format!("DROP TABLE {q}"), Risk::Destructive)
    };
    Plan {
        statements: vec![stmt(sql, risk, note.as_deref())],
        warnings: if cascade {
            vec![CASCADE_WARNING.to_string()]
        } else {
            vec![]
        },
    }
}

