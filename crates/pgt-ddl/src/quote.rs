/// Ad tırnaksız yazılabilir mi: `^[a-z_][a-z0-9_$]*$` ve anahtar sözcük değil.
fn is_plain(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else { return false };
    if !(first.is_ascii_lowercase() || first == '_') {
        return false;
    }
    if !chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '$') {
        return false;
    }
    KEYWORDS.binary_search(&name).is_err()
}

/// PG `quote_ident` ile uyumlu (ama daha tutucu): gerekirse `"…"`, içteki `"` ikilenir.
/// NUL içeren ad çağıranın hatasıdır (üreticilerde doğrulanır).
pub fn quote_ident(name: &str) -> String {
    debug_assert!(!name.contains('\0'), "ad NUL içeremez");
    if is_plain(name) {
        return name.to_string();
    }
    let mut out = String::with_capacity(name.len() + 2);
    out.push('"');
    for c in name.chars() {
        if c == '"' {
            out.push('"');
        }
        out.push(c);
    }
    out.push('"');
    out
}

/// PG `quote_literal` ile aynı: `'` ikilenir; `\` varsa `E'…'` biçimi ve `\` ikilenir.
pub fn quote_literal(s: &str) -> String {
    debug_assert!(!s.contains('\0'), "değer NUL içeremez");
    let has_backslash = s.contains('\\');
    let mut out = String::with_capacity(s.len() + 3);
    if has_backslash {
        out.push('E');
    }
    out.push('\'');
    for c in s.chars() {
        if c == '\'' || (has_backslash && c == '\\') {
            out.push(c);
        }
        out.push(c);
    }
    out.push('\'');
    out
}

/// `şema.ad`, her parça ayrı tırnaklanır.
pub fn qualified(schema: &str, name: &str) -> String {
    format!("{}.{}", quote_ident(schema), quote_ident(name))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn plain_lowercase_names_stay_unquoted() {
        assert_eq!(quote_ident("orders"), "orders");
        assert_eq!(quote_ident("_t1$x"), "_t1$x");
    }
    #[test]
    fn uppercase_space_digit_start_and_empty_are_quoted() {
        assert_eq!(quote_ident("Order Items"), "\"Order Items\"");
        assert_eq!(quote_ident("1abc"), "\"1abc\"");
        assert_eq!(quote_ident("Ünï"), "\"Ünï\"");
        assert_eq!(quote_ident(""), "\"\"");
        assert_eq!(quote_ident("$x"), "\"$x\"");
    }
    #[test]
    fn embedded_double_quotes_are_doubled() {
        assert_eq!(quote_ident("a\"b"), "\"a\"\"b\"");
        assert_eq!(quote_ident("\""), "\"\"\"\"");
    }
    #[test]
    fn injection_shaped_names_stay_one_identifier() {
        assert_eq!(quote_ident("a; drop table x"), "\"a; drop table x\"");
        assert_eq!(quote_ident("a--b"), "\"a--b\"");
        assert_eq!(quote_ident("a/*b"), "\"a/*b\"");
        assert_eq!(quote_ident("a\\b"), "\"a\\b\"");
    }
    #[test]
    fn every_keyword_is_quoted() {
        for k in KEYWORDS {
            assert!(quote_ident(k).starts_with('"'), "{k}");
        }
        assert!(KEYWORDS.windows(2).all(|w| w[0] < w[1]));
        for k in ["select", "user", "order", "table", "type", "name", "abort"] {
            assert!(KEYWORDS.binary_search(&k).is_ok(), "{k}");
        }
    }
    #[test]
    fn keywords_are_ascii_lowercase() {
        assert!(KEYWORDS.iter().all(|k| k.bytes().all(|b| b.is_ascii_lowercase() || b == b'_')));
    }
    #[test]
    fn literals() {
        assert_eq!(quote_literal("it's"), "'it''s'");
        assert_eq!(quote_literal("a\\b"), "E'a\\\\b'");
        assert_eq!(quote_literal(""), "''");
        assert_eq!(quote_literal("a\\'b"), "E'a\\\\''b'");
    }
    #[test]
    fn qualified_names() {
        assert_eq!(qualified("public", "Order"), "public.\"Order\"");
        assert_eq!(qualified("user", "t"), "\"user\".t");
    }
}
